def ke_bi(*args,**kwargs):#args将未对应的变量转化为元组，#kwarges表示把多余的未对应变量转化为字典
    print(args,kwargs)
ke_bi(1,2,3,4,5,name="小红",age=21)#将对应参数外的变量解包出来，并打包到一个字典内

def ke_bi0(first,*second):#单独用*表示把对应参数外的值打包成一个元组，这么做允许输入多余或少量参数而不报错
    print(first,second)
ke_bi0(1,2,3,4,"小明")

def ke_bi2(first,**second):#解包，单独用**意味着把传入过来的数据一一拆解出来，并放到一个字典中
    print(first)
    print(second)
ke_bi2(1,lst=[1,2,3,4],name="小明")
#有单*传参数时不能有没有定义的变量，比如传(1,2,3,4,name="小红")会报错，但是传(1,2,3,4,5,6,"小红")不会
#**表示把额外变量拆解出来，传参数必须有对应的定义的变量，比如(1,2,3,4，name="小红")会报错，但是(lst=[1,2,3,4],name="小红")会显示{'lst': [1, 2, 3, 4], 'name': '小明'}
#*和**一起用表示把没有变量的参数打包为一个元组，剩下的有定义的额外变量打包为一个字典